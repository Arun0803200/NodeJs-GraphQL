const DICTIONARIES: Record<Lang, Record<UiKey, string>> = { en, ta };
const STORAGE_KEY = "uiLang";

interface UiLangContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: UiKey, vars?: Record<string, string | number>) => string;
}

const UiLangContext = createContext<UiLangContextValue | null>(null);

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "ta") return saved;
  } catch {
    // storage blocked: fall through to browser language
  }
  return navigator.language?.toLowerCase().startsWith("ta") ? "ta" : "en";
}

export function UiLangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (next: Lang) => {
    setLangState(next);
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* not persisted */ }
  };

  const t = (key: UiKey, vars?: Record<string, string | number>) => {
    let text = DICTIONARIES[lang][key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
    return text;
  };

  return <UiLangContext.Provider value={{ lang, setLang, t }}>{children}</UiLangContext.Provider>;
}

export function useUiLang() {
  const ctx = useContext(UiLangContext);
  if (!ctx) throw new Error("useUiLang must be used within UiLangProvider");
  return ctx;
}

